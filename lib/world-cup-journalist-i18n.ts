export function normalizeWorldCupJournalistLanguage(value: string | null | undefined): WorldCupJournalistLanguage {
  const normalized = (value || '').trim().toLowerCase();
  if (normalized === 'ko' || normalized === 'ja' || normalized === 'es' || normalized === 'vi' || normalized === 'it' || normalized === 'fr') {
    return normalized;
  }
  return 'en';
}

export function getWorldCupJournalistI18n(language: WorldCupJournalistLanguage): WorldCupJournalistI18n {
  return I18N[language];
}
